-- حافظ للإلكترونيات: مخطط المتجر والطلبات
-- شغّل هذا الملف من Supabase Dashboard > SQL Editor.

create extension if not exists pgcrypto;

do $$ begin
  create type public.order_status as enum ('new', 'confirmed', 'preparing', 'shipped', 'delivered', 'cancelled');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.payment_method as enum ('cash_on_delivery', 'card_on_delivery', 'cash', 'card', 'transfer');
exception when duplicate_object then null; end $$;

create table if not exists public.products (
  id bigint primary key,
  name text not null,
  category text not null default '',
  barcode text not null unique,
  price numeric(12,2) not null check (price >= 0),
  cost numeric(12,2) not null default 0 check (cost >= 0),
  stock integer not null default 0 check (stock >= 0),
  spec text not null default '',
  image_url text,
  updated_at timestamptz not null default now()
);

create table if not exists public.online_orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique,
  created_at timestamptz not null default now(),
  status public.order_status not null default 'new',
  customer_name text not null,
  customer_phone text not null,
  city text not null,
  address text not null,
  notes text not null default '',
  payment_method public.payment_method not null,
  subtotal numeric(12,2) not null check (subtotal >= 0),
  shipping numeric(12,2) not null default 0 check (shipping >= 0),
  total numeric(12,2) not null check (total >= 0)
);

create table if not exists public.online_order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.online_orders(id) on delete cascade,
  product_id bigint not null references public.products(id),
  product_name text not null,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0)
);

create index if not exists online_orders_created_at_idx on public.online_orders(created_at desc);
create index if not exists online_order_items_order_id_idx on public.online_order_items(order_id);

alter table public.products enable row level security;
alter table public.online_orders enable row level security;
alter table public.online_order_items enable row level security;

drop policy if exists "public can read products" on public.products;
create policy "public can read products" on public.products for select using (true);

-- لا نسمح للزائر بإدخال طلب خام مباشرة؛ الإدخال يتم عبر الدالة الذرية أدناه.
drop policy if exists "authenticated can manage products" on public.products;
create policy "authenticated can manage products" on public.products for all to authenticated using (true) with check (true);

-- الإدارة فقط تقرأ وتحدّث الطلبات بعد تسجيل الدخول.
drop policy if exists "authenticated can manage online orders" on public.online_orders;
create policy "authenticated can manage online orders" on public.online_orders for select to authenticated using (true);
create policy "authenticated can update online orders" on public.online_orders for update to authenticated using (true) with check (true);
drop policy if exists "authenticated can read order items" on public.online_order_items;
create policy "authenticated can read order items" on public.online_order_items for select to authenticated using (true);

create or replace function public.create_online_order(
  p_customer_name text,
  p_customer_phone text,
  p_city text,
  p_address text,
  p_notes text,
  p_payment_method public.payment_method,
  p_shipping numeric,
  p_items jsonb
) returns table(order_id uuid, order_number text, total numeric)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order_id uuid;
  v_order_number text := '#WEB-' || floor(extract(epoch from clock_timestamp()) * 1000)::bigint::text;
  v_subtotal numeric := 0;
  v_total numeric;
  v_item jsonb;
  v_product products%rowtype;
  v_quantity integer;
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'cart_empty';
  end if;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_quantity := (v_item->>'quantity')::integer;
    select * into v_product from products where id = (v_item->>'product_id')::bigint for update;
    if not found or v_quantity < 1 or v_product.stock < v_quantity then
      raise exception 'product_unavailable';
    end if;
    v_subtotal := v_subtotal + (v_product.price * v_quantity);
  end loop;

  v_total := v_subtotal + greatest(coalesce(p_shipping, 0), 0);
  insert into online_orders(order_number, customer_name, customer_phone, city, address, notes, payment_method, subtotal, shipping, total)
  values (v_order_number, trim(p_customer_name), trim(p_customer_phone), trim(p_city), trim(p_address), coalesce(p_notes, ''), p_payment_method, v_subtotal, greatest(coalesce(p_shipping, 0), 0), v_total)
  returning id into v_order_id;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_quantity := (v_item->>'quantity')::integer;
    select * into v_product from products where id = (v_item->>'product_id')::bigint for update;
    insert into online_order_items(order_id, product_id, product_name, unit_price, quantity)
    values (v_order_id, v_product.id, v_product.name, v_product.price, v_quantity);
    update products set stock = stock - v_quantity, updated_at = now() where id = v_product.id;
  end loop;

  return query select v_order_id, v_order_number, v_total;
end;
$$;

grant execute on function public.create_online_order(text, text, text, text, text, public.payment_method, numeric, jsonb) to anon, authenticated;
